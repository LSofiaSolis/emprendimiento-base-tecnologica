create table public.sonora_admin (
 email text primary key, sal text not null, hash text not null
);
create table public.sonora_locales (
 id uuid primary key default gen_random_uuid(),
 nombre text not null check(length(nombre) between 2 and 80),
 tipo text not null default 'Cafetería',
 codigo_hash text unique not null,
 activo boolean not null default true,
 abierto boolean not null default true,
 pista_actual integer,
 creado timestamptz not null default now()
);
create table public.sonora_pistas (
 id integer generated by default as identity primary key,
 titulo text not null, artista text not null, genero text not null,
 duracion integer not null check(duracion between 1 and 3600),
 fuente text not null, licencia text not null,
 audio_url text, activo boolean not null default true
);
create table public.sonora_sesiones (
 hash text primary key, rol text not null check(rol in ('admin','dueno','visitante')),
 local_id uuid references public.sonora_locales(id) on delete cascade,
 vence timestamptz not null default now()+interval '12 hours'
);
create table public.sonora_cola (
 id uuid primary key default gen_random_uuid(),
 local_id uuid not null references public.sonora_locales(id) on delete cascade,
 pista_id integer not null references public.sonora_pistas(id),
 estado text not null default 'pendiente' check(estado in ('pendiente','aprobada','rechazada','reproducida')),
 creado timestamptz not null default now()
);
create unique index sonora_cola_activa_idx on public.sonora_cola(local_id,pista_id) where estado in ('pendiente','aprobada');
create table public.sonora_votos (
 cola_id uuid not null references public.sonora_cola(id) on delete cascade,
 visitante text not null references public.sonora_sesiones(hash) on delete cascade,
 primary key(cola_id,visitante)
);
create index sonora_cola_local_idx on public.sonora_cola(local_id);
create index sonora_sesiones_local_idx on public.sonora_sesiones(local_id);
create index sonora_votos_visitante_idx on public.sonora_votos(visitante);
